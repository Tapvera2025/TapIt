import { ApplicationError } from '../../../errors.js';

export const ACCOUNTING_ERROR_CODES = {
  ACCOUNT_NOT_FOUND: 'ACCOUNTING_ACCOUNT_NOT_FOUND',
  PERIOD_NOT_FOUND: 'ACCOUNTING_PERIOD_NOT_FOUND',
  SYSTEM_ACCOUNT: 'ACCOUNTING_SYSTEM_ACCOUNT',
  INVALID_PERIOD: 'ACCOUNTING_INVALID_PERIOD',
  PERIOD_NOT_CLOSABLE: 'ACCOUNTING_PERIOD_NOT_CLOSABLE',
  PERIOD_CLOSED: 'ACCOUNTING_PERIOD_CLOSED',
  JOURNAL_UNBALANCED: 'ACCOUNTING_JOURNAL_UNBALANCED',
  JOURNAL_EMPTY: 'ACCOUNTING_JOURNAL_EMPTY',
  JOURNAL_IMMUTABLE: 'ACCOUNTING_JOURNAL_IMMUTABLE',
  JOURNAL_NOT_FOUND: 'ACCOUNTING_JOURNAL_NOT_FOUND',
  JOURNAL_ALREADY_REVERSED: 'ACCOUNTING_JOURNAL_ALREADY_REVERSED',
  ACCOUNT_INACTIVE: 'ACCOUNTING_ACCOUNT_INACTIVE',
  CLOSE_CHECKLIST_INCOMPLETE: 'ACCOUNTING_CLOSE_CHECKLIST_INCOMPLETE',
  CLOSE_SELF_POSTING: 'ACCOUNTING_CLOSE_SELF_POSTING',
  PERIOD_OVERLAP: 'ACCOUNTING_PERIOD_OVERLAP',
} as const;

export class AccountingNotFoundError extends ApplicationError {
  constructor(message: string, code: string) {
    super(message, 404, code);
    this.name = 'AccountingNotFoundError';
  }
}

export class AccountingValidationError extends ApplicationError {
  constructor(message: string, code: string = ACCOUNTING_ERROR_CODES.INVALID_PERIOD) {
    super(message, 422, code);
    this.name = 'AccountingValidationError';
  }
}
